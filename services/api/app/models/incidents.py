"""Pydantic models for centralized incident manager and CSV analysis."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

IncidentStatus = Literal["open", "in_progress", "resolved", "discarded"]
IncidentOrigin = Literal["customer", "branch", "internal"]
IncidentCategory = Literal[
    "clinical_equipment",
    "it_system",
    "billing_error",
    "compliance_breach",
    "patient_experience",
    "staff_issue",
    "facility_issue",
    "referral_issue",
    "other",
]
IncidentBranch = Literal[
    "central",
    "austin_north",
    "dallas_uptown",
    "houston_med_center",
    "san_antonio_west",
    "miami_brickell",
    "miami_doral",
    "orlando_east",
    "tampa_bay",
    "atlanta_midtown",
    "savannah",
    "london_city",
    "london_west",
    "manchester_central",
]


class IncidentAnalyzeResponse(BaseModel):
    total_processed: int
    total_valid: int
    total_invalid: int
    invalid_by_type: dict[str, int]
    by_category: dict[str, int]
    by_status: dict[str, int]
    avg_satisfaction_closed: float | None
    closed_with_score_count: int


class IncidentRecord(BaseModel):
    """One managed incident. Never includes patient identifiers."""

    id: str
    title: str
    description: str
    category: IncidentCategory
    status: IncidentStatus
    origin: IncidentOrigin
    branch: IncidentBranch
    created_at: str
    updated_at: str


class IncidentListResponse(BaseModel):
    total: int
    items: list[IncidentRecord]


class IncidentCreate(BaseModel):
    """Registration form body. Id and timestamps are generated by the API."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(min_length=1, max_length=200)
    description: str = Field(min_length=1, max_length=8000)
    category: IncidentCategory
    status: IncidentStatus = "open"
    origin: IncidentOrigin
    branch: IncidentBranch


class IncidentStatusUpdate(BaseModel):
    """The only body PATCH /api/incidents/{id}/status accepts."""

    model_config = ConfigDict(extra="forbid")

    status: IncidentStatus


class IncidentSummaryResponse(BaseModel):
    by_status: dict[str, int]
    by_category: dict[str, int]
    by_origin: dict[str, int]
    by_branch: dict[str, int]
    total: int
